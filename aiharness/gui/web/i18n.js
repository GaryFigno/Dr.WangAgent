const I18N_HTML_LANG = {
  zh: "zh-CN",
  "zh-TW": "zh-TW",
  en: "en",
  ja: "ja",
  ko: "ko",
  es: "es",
  fr: "fr",
  de: "de",
  pt: "pt",
  ru: "ru",
  vi: "vi",
  id: "id",
};

let _locale = "zh";
let _pref = "auto";

function detectBrowserLanguage() {
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
  const raw = String(nav).toLowerCase().replace("_", "-");
  if (raw.startsWith("zh-tw") || raw.startsWith("zh-hk") || raw.includes("hant")) return "zh-TW";
  if (raw.startsWith("zh")) return "zh";
  const base = raw.split("-")[0];
  if (I18N_CATALOG[base]) return base;
  return "en";
}

function resolveLocale(pref) {
  const code = pref || "auto";
  if (code === "auto") return detectBrowserLanguage();
  if (I18N_CATALOG[code]) return code;
  return "en";
}

function t(key, vars) {
  const tables = [_locale, ...I18N_FALLBACK];
  let text;
  for (const loc of tables) {
    const table = I18N_CATALOG[loc];
    if (table && table[key] != null) {
      text = table[key];
      break;
    }
  }
  if (text == null) text = key;
  if (vars) {
    text = String(text).replace(/\{(\w+)\}/g, (_, name) =>
      vars[name] != null ? String(vars[name]) : `{${name}}`,
    );
  }
  return text;
}

function setLanguagePreference(pref) {
  _pref = pref || "auto";
  _locale = resolveLocale(_pref);
  try {
    localStorage.setItem("aih.language", _pref);
  } catch {
    /* ignore */
  }
  applyI18n();
  return _locale;
}

function currentLanguagePref() {
  return _pref;
}

function currentLocale() {
  return _locale;
}

function applyI18n(root) {
  const scope = root || document;
  document.documentElement.lang = I18N_HTML_LANG[_locale] || _locale;
  scope.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (!key) return;
    const value = t(key);
    if (node.dataset.i18nHtml === "1") node.innerHTML = value;
    else node.textContent = value;
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.getAttribute("data-i18n-placeholder");
    if (key) node.setAttribute("placeholder", t(key));
  });
  scope.querySelectorAll("[data-i18n-title]").forEach((node) => {
    const key = node.getAttribute("data-i18n-title");
    if (key) node.setAttribute("title", t(key));
  });
  for (const selectId of ["mode-select", "codex-mode-select", "claude-mode-select"]) {
    const optAsk = document.querySelector(`#${selectId} option[value="ask"]`);
    const optAuto = document.querySelector(`#${selectId} option[value="auto"]`);
    const optYolo = document.querySelector(`#${selectId} option[value="yolo"]`);
    if (optAsk) optAsk.textContent = t("mode.ask");
    if (optAuto) optAuto.textContent = t("mode.auto");
    if (optYolo) optYolo.textContent = t("mode.yolo");
  }
}

function bootLanguageFromStorage() {
  let pref = "auto";
  try {
    pref = localStorage.getItem("aih.language") || "auto";
  } catch {
    pref = "auto";
  }
  setLanguagePreference(pref);
}

// Eager apply so first paint is closer to the saved language.
if (typeof document !== "undefined") {
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", bootLanguageFromStorage);
  } else {
    bootLanguageFromStorage();
  }
}
